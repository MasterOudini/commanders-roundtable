// `Thaumaturge's Familiar` — the ETB scry behind a flying keyword line the
// engine already enforces; the def claims only the trigger (Galadhrim Guide's
// shape, D215). D258.

import { THAUMATURGE_S_FAMILIAR } from '../../../data/fixtures/engineCards';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const PRINTED = printed(THAUMATURGE_S_FAMILIAR, 'Flying\nWhen this creature enters, scry 1.');
const TEXT = PRINTED.split('\n')[1] as string;

export const THAUMATURGES_FAMILIAR_SCRIPT: CardScript = {
  oracleId: THAUMATURGE_S_FAMILIAR.oracleId,
  name: THAUMATURGE_S_FAMILIAR.name,
  triggers: [
    {
      abilityId: 'etb-scry',
      text: TEXT,
      event: 'CardsMoved',
      activeZones: ['battlefield'],
      optional: false,
      matches: (_ctx, self, ev) =>
        ev.t === 'CardsMoved' &&
        ev.moves.some(
          (m) => m.card === self && m.to.kind === 'battlefield' && m.from.kind !== 'battlefield',
        ),
      label: () => "Thaumaturge's Familiar — scry 1",
      resolve: (ctx, _self, obj): readonly EventBody[] => {
        const library = ctx.state.zones.library[obj.controller] ?? [];
        const n = Math.min(1, library.length);
        if (n === 0) return [];
        const top = library.slice(library.length - n);
        return [
          { t: 'CardsRevealed', cards: top, to: [obj.controller] },
          {
            t: 'AwaitingSet',
            awaiting: {
              kind: 'scryChoice',
              player: obj.controller,
              count: n,
              toGraveyard: false,
              thenDraw: 0,
              label: obj.label,
            },
          },
        ];
      },
    },
  ],
};
