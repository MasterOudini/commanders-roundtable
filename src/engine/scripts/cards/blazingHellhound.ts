// `Blazing Hellhound` — "{1}, Sacrifice another creature: This creature deals
// 1 damage to any target." The chooser's "another" exclusion on a source that
// IS a legal kind for its own predicate — the Hellhound can never feed
// itself, exactly Ahriman's rule with a ping behind it. M6.4l, D169.

import { BLAZING_HELLHOUND } from '../../../data/fixtures/engineCards';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const TEXT = printed(
  BLAZING_HELLHOUND,
  '{1}, Sacrifice another creature: This creature deals 1 damage to any target.',
);

export const BLAZING_HELLHOUND_SCRIPT: CardScript = {
  oracleId: BLAZING_HELLHOUND.oracleId,
  name: BLAZING_HELLHOUND.name,
  activated: [
    {
      ref: `${BLAZING_HELLHOUND.oracleId}#a0`,
      text: TEXT,
      resolve: (ctx, self, obj): readonly EventBody[] => {
        const target = obj.targets[0];
        if (!target || target.kind === 'stack') return [];
        if (target.kind === 'card' && ctx.state.cards[target.id]?.zone.kind !== 'battlefield') {
          return [];
        }
        const d = ctx.derive(self);
        const infect = d.keywords.has('infect');
        const wither = d.keywords.has('wither');
        return [
          {
            t: 'DamageDealt',
            damages: [
              {
                source: self,
                target:
                  target.kind === 'player'
                    ? { kind: 'player', id: target.id }
                    : { kind: 'card', id: target.id },
                amount: 1,
                deathtouch: d.keywords.has('deathtouch'),
                lifelinkTo: d.keywords.has('lifelink') ? obj.controller : null,
                isCommanderDamage: false,
                viaTrample: 0,
                toxic: d.toxicAmount,
                applyAs:
                  target.kind === 'player' && infect ? 'poison' : infect || wither ? 'wither' : 'normal',
              },
            ],
          },
        ];
      },
    },
  ],
};
