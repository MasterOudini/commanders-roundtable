// `Thornwind Faeries` — the {T} ping at any target (Flamekin Spitfire's
// shape, D175), behind a flying keyword line the engine already enforces. The
// per-kind `applyAs` branch is written at first cut: infect versus a PLAYER
// is poison, versus a creature is wither (D174's correction). D259.

import { THORNWIND_FAERIES } from '../../../data/fixtures/engineCards';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const PRINTED = printed(
  THORNWIND_FAERIES,
  'Flying\n{T}: This creature deals 1 damage to any target.',
);
const TEXT = PRINTED.split('\n')[1] as string;

export const THORNWIND_FAERIES_SCRIPT: CardScript = {
  oracleId: THORNWIND_FAERIES.oracleId,
  name: THORNWIND_FAERIES.name,
  activated: [
    {
      ref: `${THORNWIND_FAERIES.oracleId}#a0`,
      text: TEXT,
      resolve: (ctx, self, obj): readonly EventBody[] => {
        const target = obj.targets[0];
        if (!target) return [];
        if (target.kind === 'card' && ctx.state.cards[target.id]?.zone.kind !== 'battlefield')
          return [];
        const d = ctx.derive(self);
        return [
          {
            t: 'DamageDealt',
            damages: [
              {
                source: self,
                target:
                  target.kind === 'player'
                    ? { kind: 'player', id: target.id }
                    : { kind: 'card', id: target.id },
                amount: 1,
                deathtouch: d.keywords.has('deathtouch'),
                lifelinkTo: d.keywords.has('lifelink') ? obj.controller : null,
                isCommanderDamage: false,
                viaTrample: 0,
                toxic: d.toxicAmount,
                applyAs: d.keywords.has('infect')
                  ? target.kind === 'player'
                    ? 'poison'
                    : 'wither'
                  : d.keywords.has('wither') && target.kind === 'card'
                    ? 'wither'
                    : 'normal',
              },
            ],
          },
        ];
      },
    },
  ],
};
