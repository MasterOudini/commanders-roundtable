// `Goblin Bombardment` — "Sacrifice a creature: This enchantment deals 1
// damage to any target." The D168 sacrifice chooser with NO mana — the
// creature IS the price — on an enchantment-source ping through D169's
// staged chain. M6.4u, D177.

import { GOBLIN_BOMBARDMENT } from '../../../data/fixtures/engineCards';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const TEXT = printed(
  GOBLIN_BOMBARDMENT,
  'Sacrifice a creature: This enchantment deals 1 damage to any target.',
);

export const GOBLIN_BOMBARDMENT_SCRIPT: CardScript = {
  oracleId: GOBLIN_BOMBARDMENT.oracleId,
  name: GOBLIN_BOMBARDMENT.name,
  activated: [
    {
      // The card's whole text is this one ability: index 0.
      ref: `${GOBLIN_BOMBARDMENT.oracleId}#a0`,
      text: TEXT,
      resolve: (ctx, self, obj): readonly EventBody[] => {
        const target = obj.targets[0];
        if (!target) return [];
        if (target.kind === 'card' && ctx.state.cards[target.id]?.zone.kind !== 'battlefield')
          return [];
        const d = ctx.derive(self);
        return [
          {
            t: 'DamageDealt',
            damages: [
              {
                source: self,
                target:
                  target.kind === 'player'
                    ? { kind: 'player', id: target.id }
                    : { kind: 'card', id: target.id },
                amount: 1,
                deathtouch: d.keywords.has('deathtouch'),
                lifelinkTo: d.keywords.has('lifelink') ? obj.controller : null,
                isCommanderDamage: false,
                viaTrample: 0,
                toxic: d.toxicAmount,
                applyAs: d.keywords.has('infect')
                  ? target.kind === 'player'
                    ? 'poison'
                    : 'wither'
                  : d.keywords.has('wither') && target.kind === 'card'
                    ? 'wither'
                    : 'normal',
              },
            ],
          },
        ];
      },
    },
  ],
};
