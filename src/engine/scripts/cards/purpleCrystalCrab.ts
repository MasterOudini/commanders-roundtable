// `Purple-Crystal Crab` — "When this creature dies, draw a card."
// Palace Familiar's line in a shell. D236.

import { PURPLE_CRYSTAL_CRAB } from '../../../data/fixtures/engineCards';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';
import { drawEvents } from '../../effects';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const TEXT = printed(PURPLE_CRYSTAL_CRAB, 'When this creature dies, draw a card.');

export const PURPLE_CRYSTAL_CRAB_SCRIPT: CardScript = {
  oracleId: PURPLE_CRYSTAL_CRAB.oracleId,
  name: PURPLE_CRYSTAL_CRAB.name,
  triggers: [
    {
      abilityId: 'dies-draw',
      text: TEXT,
      event: 'CardsMoved',
      activeZones: ['battlefield'],
      looksBack: true,
      optional: false,
      matches: (_ctx, self, ev) =>
        ev.t === 'CardsMoved' &&
        ev.moves.some(
          (m) => m.card === self && m.from.kind === 'battlefield' && m.to.kind === 'graveyard',
        ),
      label: () => 'Purple-Crystal Crab — draw a card',
      resolve: (ctx, _self, obj): readonly EventBody[] => {
        const player = ctx.state.players[obj.controller];
        if (!player || player.hasLost) return [];
        return [...drawEvents(ctx.state, obj.controller, 1)];
      },
    },
  ],
};
