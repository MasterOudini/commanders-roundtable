// `Braingeyser` — "Target player draws X cards." The X read + THE draw
// rule at the TARGET. D201.

import { BRAINGEYSER } from '../../../data/fixtures/engineCards';
import { drawEvents } from '../../effects';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const TEXT = printed(BRAINGEYSER, 'Target player draws X cards.');

export const BRAINGEYSER_SCRIPT: CardScript = {
  oracleId: BRAINGEYSER.oracleId,
  name: BRAINGEYSER.name,
  spell: {
    text: TEXT,
    resolve: (ctx, _self, obj): readonly EventBody[] => {
      const x = obj.xValue ?? 0;
      if (x <= 0) return [];
      const target = obj.targets[0];
      if (!target || target.kind !== 'player') return [];
      const p = ctx.state.players[target.id];
      if (!p || p.hasLost) return [];
      return [...drawEvents(ctx.state, target.id, x)];
    },
  },
};
