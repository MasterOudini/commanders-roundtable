// `Opposition` — tap an untapped creature I control (D286's tap-cost
// chooser): tap an artifact, creature, or land (D293's list).

import { OPPOSITION } from '../../../data/fixtures/engineCards';
import type { CardData } from '../../../data/cardTypes';
import type { CardScript } from '../api';
import type { EventBody } from '../../types/events';

function printed(card: CardData, expected: string): string {
  const actual = card.faces[0]?.oracleText;
  if (actual !== expected) {
    throw new Error(
      `${card.name} reads "${actual}" and its script was written for "${expected}". ` +
        'Re-read the card before re-registering it (D90).',
    );
  }
  return expected;
}

const TEXT = printed(OPPOSITION, 'Tap an untapped creature you control: Tap target artifact, creature, or land.');

export const OPPOSITION_SCRIPT: CardScript = {
  oracleId: OPPOSITION.oracleId,
  name: OPPOSITION.name,
  activated: [
    {
      ref: `${OPPOSITION.oracleId}#a0`,
      text: TEXT,
      resolve: (ctx, _self, obj): readonly EventBody[] => {
        const target = obj.targets[0];
        if (!target || target.kind !== 'card') return [];
        const card = ctx.state.cards[target.id];
        if (!card || card.zone.kind !== 'battlefield' || card.tapped) return [];
        return [{ t: 'PermanentsTapped', cards: [target.id] }];
      },
    },
  ],
};
