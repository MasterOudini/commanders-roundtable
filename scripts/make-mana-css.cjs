/**
 * Generates src/styles/mana.generated.css from the installed mana-font package.
 *
 * Why not just `@import 'mana-font/css/mana.css'`: that stylesheet declares two
 * @font-face families with four format fallbacks each, so Vite emits EIGHT font
 * files — 4.5 MB — of which the app uses exactly one:
 *
 *   mana.eot 408K · mana.woff 408K · mana.ttf 408K · mana.svg 1.9M   (we want woff2)
 *   mplantin.{eot,woff,ttf,svg} ~3 MB                                (never referenced)
 *
 * mana-font 1.18's CSS predates woff2, so it would also load the 408 KB woff when
 * a 187 KB woff2 sits right beside it in the package.
 *
 * So: keep the package's glyph map (it is the maintained source of truth for
 * ~700 codepoints — hand-copying it would rot), drop its @font-face blocks, and
 * declare our own woff2-only one. Result: one 187 KB asset.
 *
 * Re-run after bumping mana-font:  node scripts/make-mana-css.cjs
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC_CSS = path.join(ROOT, 'node_modules', 'mana-font', 'css', 'mana.css');
const SRC_WOFF2 = path.join(ROOT, 'node_modules', 'mana-font', 'fonts', 'mana.woff2');
const OUT = path.join(ROOT, 'src', 'styles', 'mana.generated.css');

function main() {
  if (!fs.existsSync(SRC_CSS)) {
    console.error(`[mana-css] ${SRC_CSS} is missing. Run \`npm install\` first.`);
    process.exit(1);
  }
  if (!fs.existsSync(SRC_WOFF2)) {
    console.error(`[mana-css] mana.woff2 is missing from the package — check the version.`);
    process.exit(1);
  }

  const version = require(path.join(ROOT, 'node_modules', 'mana-font', 'package.json')).version;
  const original = fs.readFileSync(SRC_CSS, 'utf8');

  // Strip every @font-face block. They are top-level and non-nested, so a
  // brace-balanced scan from each occurrence is exact (a regex on `{[^}]*}`
  // would work today but breaks the moment a block gains a nested rule).
  let stripped = '';
  let cursor = 0;
  let removed = 0;
  for (;;) {
    const at = original.indexOf('@font-face', cursor);
    if (at === -1) {
      stripped += original.slice(cursor);
      break;
    }
    stripped += original.slice(cursor, at);
    const open = original.indexOf('{', at);
    if (open === -1) throw new Error('malformed @font-face: no opening brace');
    let depth = 0;
    let i = open;
    for (; i < original.length; i++) {
      if (original[i] === '{') depth++;
      else if (original[i] === '}') {
        depth--;
        if (depth === 0) break;
      }
    }
    if (depth !== 0) throw new Error('malformed @font-face: unbalanced braces');
    cursor = i + 1;
    removed++;
  }

  if (removed !== 2) {
    // The package shipped a different number of families than we expect. Fail
    // loudly rather than silently emitting a stylesheet with no usable font.
    console.error(`[mana-css] Expected 2 @font-face blocks, found ${removed}. Inspect mana.css before trusting this output.`);
    process.exit(1);
  }

  // Path is relative to the generated file's own location, which is how Vite
  // resolves url() in CSS. A bare package specifier is not resolved here.
  const header = `/* GENERATED by scripts/make-mana-css.cjs — DO NOT EDIT BY HAND.
 * Source: mana-font@${version} (fonts SIL OFL 1.1, code MIT — Andrew Gioia).
 * The package's own @font-face blocks were removed and replaced with the woff2
 * declaration below; see the script for why. Re-run the script after upgrading
 * mana-font. ${removed} @font-face block(s) stripped, glyph map kept verbatim.
 */
@font-face {
  font-family: "Mana";
  src: url("../../node_modules/mana-font/fonts/mana.woff2") format("woff2");
  font-weight: normal;
  font-style: normal;
  font-display: block; /* icon font: a swap would flash wrong glyphs, not text */
}
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header + stripped.trimStart(), 'utf8');

  const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
  console.log(`[mana-css] Wrote ${path.relative(ROOT, OUT)} (${kb(header.length + stripped.length)}), ` +
    `1 font asset (${kb(fs.statSync(SRC_WOFF2).size)}) instead of 8 (~4.5 MB).`);
}

main();
